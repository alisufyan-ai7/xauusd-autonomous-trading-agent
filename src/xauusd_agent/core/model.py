    STARTUP_INTEGRITY_FAILED = "STARTUP_INTEGRITY_FAILED"
    WRITER_LEASE_UNAVAILABLE = "WRITER_LEASE_UNAVAILABLE"
    WRITER_LEASE_LOST = "WRITER_LEASE_LOST"
